    private void btnPesquisarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPesquisarActionPerformed
        String ipServidor = "127.0.0.1";
        try {
    Registry registro =
        LocateRegistry.getRegistry(ipServidor, 1099);

    TelefoniaService servico =
        (TelefoniaService) registro.lookup("TelefoniaService");

    Sessao sessao = servico.consultarSessao(
        txtNumero.getText().trim()
    );

    if (sessao == null) {
        txtDados.setText(
            "Número de celular não encontrado."
        );
    } else {
        txtDados.setText(sessao.toString());
    }

} catch (Exception e) {
    JOptionPane.showMessageDialog(
        this, "Erro na comunicação com o servidor: "
        + e.getMessage()
    );
}
    }//GEN-LAST:event_btnPesquisarActionPerformed

