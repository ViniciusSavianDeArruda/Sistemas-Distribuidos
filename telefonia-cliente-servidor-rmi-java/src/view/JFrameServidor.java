    private void iniciarServidor() {
    try {
        System.setProperty(
            "java.rmi.server.hostname",
            "127.0.0.1"
        );
        Registry registro = LocateRegistry.createRegistry(1099);

        registro.rebind(
            "TelefoniaService",
            new TelefoniaServiceImpl(hashSessoes)
        );

        JOptionPane.showMessageDialog(
            this, "Servidor RMI iniciado!"+ "IP:127.0.0.1\n" + "Porta do registro: 1099"
        );

    } catch (Exception e) {
        JOptionPane.showMessageDialog(
            this,
            "Erro ao iniciar servidor: " + e.getMessage()
        );
    }
}
    
    private void carregarSessoes() {
    StringBuilder dadosSessoes = new StringBuilder();

    String resposta = Util.carregarArquivoEmHashMap(
        hashSessoes.sessoes,
        dadosSessoes
    );

    if (!resposta.isEmpty()) {
        JOptionPane.showMessageDialog(
            this,
            resposta,
            "Erro ao carregar arquivo",
            JOptionPane.ERROR_MESSAGE
        );
        return;
    }

    jTextAreaDadosSessoes.setText(dadosSessoes.toString());
    iniciarServidor();
}

